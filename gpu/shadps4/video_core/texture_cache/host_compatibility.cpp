bool IsVulkanFormatCompatible(Backend::Format base, Backend::Format view) {
    if (base == view) {
        return true;
    }
    const auto base_comp = FORMAT_TABLE.at(base);
    const auto view_comp = FORMAT_TABLE.at(view);
    return (base_comp & view_comp) == view_comp;
}

