#!/usr/bin/env python3
"""tools/vk_caps_fields.py [VULKAN_CORE_H]: writes gpu/shadps4/video_core/renderer_metal/
mtl_vk_caps_fields.inc, the members of the feature and property structures the renderer asks the
Vulkan driver for (Instance::CreateDevice's chains), one BB_FIELD(struct, member) each after a
BB_STRUCT(struct), without sType and pNext. The Metal backend's comparison with MoltenVK's answers
(BB_METAL_CAPS=compare; docs/RENDER_ADAPTER.md, M4 step 4.1) names differing fields with it. Run it
again when the Vulkan headers or the chains change."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
header = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'deps/macos-arm64/include/vulkan/vulkan_core.h'
out = ROOT / 'gpu/shadps4/video_core/renderer_metal/mtl_vk_caps_fields.inc'

STRUCTS = [
    # Features (Instance::CreateDevice's getFeatures2 chain).
    'VkPhysicalDeviceFeatures', 'VkPhysicalDeviceVulkan11Features', 'VkPhysicalDeviceVulkan12Features',
    'VkPhysicalDeviceVulkan13Features', 'VkPhysicalDeviceRobustness2FeaturesKHR',
    'VkPhysicalDeviceExtendedDynamicState3FeaturesEXT',
    'VkPhysicalDevicePrimitiveTopologyListRestartFeaturesEXT',
    'VkPhysicalDeviceShaderAtomicFloat2FeaturesEXT',
    'VkPhysicalDeviceWorkgroupMemoryExplicitLayoutFeaturesKHR',
    'VkPhysicalDeviceImage2DViewOf3DFeaturesEXT', 'VkPhysicalDeviceShaderClockFeaturesKHR',
    'VkPhysicalDeviceComputeShaderDerivativesFeaturesKHR',
    'VkPhysicalDeviceShaderMixedFloatDotProductFeaturesVALVE',
    'VkPhysicalDeviceCooperativeMatrixFeaturesKHR', 'VkPhysicalDeviceShaderFloat8FeaturesEXT',
    # Properties (its getProperties2 chains).
    'VkPhysicalDeviceProperties', 'VkPhysicalDeviceLimits', 'VkPhysicalDeviceSparseProperties',
    'VkPhysicalDeviceVulkan11Properties', 'VkPhysicalDeviceVulkan12Properties',
    'VkPhysicalDeviceVulkan13Properties', 'VkPhysicalDevicePushDescriptorProperties',
    'VkPhysicalDeviceDriverProperties',
]

text = header.read_text()
lines = ['// Generated by tools/vk_caps_fields.py from vulkan_core.h: do not edit.']
for name in STRUCTS:
    m = re.search(r'typedef struct ' + name + r' \{(.*?)\} ' + name + ';', text, re.S)
    if not m:
        sys.exit(f'{name}: not in {header}')
    lines.append(f'BB_STRUCT({name})')
    for member in m.group(1).split(';'):
        member = member.strip()
        if not member:
            continue
        fm = re.search(r'^(?:const\s+)?([\w\s*]+?)\s+(\w+)\s*(\[[^\]]*\])?$', member)
        ctype, field, array = fm.group(1).strip(), fm.group(2), fm.group(3)
        if field in ('sType', 'pNext') or ctype in ('VkPhysicalDeviceLimits', 'VkPhysicalDeviceSparseProperties'):
            continue  # nested structures are compared on their own
        # How to print it: B a VkBool32, U 32-bit integer, F float, Q 64-bit, S text, X bytes.
        if array:
            kind = 'S' if ctype == 'char' else 'X'
        elif ctype == 'VkBool32':
            kind = 'B'
        elif ctype == 'float':
            kind = 'F'
        elif ctype in ('VkDeviceSize', 'uint64_t', 'size_t', 'int64_t'):
            kind = 'Q'
        elif ctype in ('uint32_t', 'int32_t') or ctype.startswith('Vk'):
            kind = 'U'
        else:
            kind = 'X'
        lines.append(f'BB_FIELD({name}, {field}, {kind})')
out.write_text('\n'.join(lines) + '\n')
print(f'{len(STRUCTS)} structures, {sum(l.startswith("BB_FIELD") for l in lines)} fields -> {out.relative_to(ROOT)}')
