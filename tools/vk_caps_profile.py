#!/usr/bin/env python3
"""tools/vk_caps_profile.py LOG: writes gpu/shadps4/video_core/renderer_metal/mtl_vk_caps_profile.inc
from the "Metal caps:" lines of a BB_METAL_CAPS=compare log taken while the Metal backend answered
nothing: MoltenVK's answers on that Mac (docs/RENDER_ADAPTER.md, M4 step 4.1). The Metal backend
starts from this profile; what depends on the device (its name, memory, buffer and threadgroup
limits) is read from the MTLDevice in mtl_vk_caps.mm. A comparison on other Macs shows what else
varies."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
out = ROOT / 'gpu/shadps4/video_core/renderer_metal/mtl_vk_caps_profile.inc'
lines = pathlib.Path(sys.argv[1]).read_text(errors='replace').splitlines()

gpu = next((l.split('GPU: ', 1)[1].split(' (')[0] for l in lines if l.startswith('GPU: ')), 'unknown GPU')
values, formats, types, heaps, families, extensions = [], {}, [], [], [], []
for line in lines:
    if not line.startswith('Metal caps: '):
        continue
    body = line[len('Metal caps: '):]
    if m := re.match(r'(Vk\w+)\.(\w+): MoltenVK (.*), Metal .*$', body):
        values.append((m.group(1), m.group(2), m.group(3)))
    elif m := re.match(r'format (\d+) \(\w+\) (linear|optimal|buffer): MoltenVK (0x[0-9a-f]+|0),', body):
        formats.setdefault(int(m.group(1)), {})[m.group(2)] = m.group(3)
    elif m := re.match(r'memory type \d+: MoltenVK flags (0x[0-9a-f]+|0) heap (\d+)', body):
        types.append((m.group(1), m.group(2)))
    elif m := re.match(r'memory heap \d+: MoltenVK (\d+) bytes flags (0x[0-9a-f]+|0)', body):
        heaps.append((m.group(1), m.group(2)))
    elif m := re.match(r'queue family \d+: MoltenVK flags (0x[0-9a-f]+|0) count (\d+) timestamp bits (\d+) '
                       r'granularity (\d+)x(\d+)x(\d+)', body):
        families.append(m.groups())
    elif body.startswith('extensions only MoltenVK has'):
        extensions = body.split(':', 1)[1].split()

def cstr(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'

result = [f'// Generated by tools/vk_caps_profile.py: MoltenVK\'s answers on an {gpu} (BB_METAL_CAPS=compare).',
          '// Do not edit; values that depend on the device are set in mtl_vk_caps.mm.']
for structure, field, value in values:
    result.append(f'BB_VALUE({structure}, {field}, {cstr(value)})')
for f in sorted(formats):
    v = formats[f]
    result.append(f'BB_FORMAT({f}, {v.get("linear", "0")}, {v.get("optimal", "0")}, {v.get("buffer", "0")})')
for flags, heap in types:
    result.append(f'BB_MEMORY_TYPE({flags}, {heap})')
for size, flags in heaps:
    result.append(f'BB_MEMORY_HEAP({size}ull, {flags})')
for flags, count, bits, w, h, d in families:
    result.append(f'BB_QUEUE_FAMILY({flags}, {count}, {bits}, {w}, {h}, {d})')
for e in extensions:
    result.append(f'BB_EXTENSION({cstr(e)})')
out.write_text('\n'.join(result) + '\n')
print(f'{gpu}: {len(values)} values, {len(formats)} formats, {len(types)} memory types, {len(heaps)} heaps, '
      f'{len(families)} queue families, {len(extensions)} extensions -> {out.relative_to(ROOT)}')
