#!/usr/bin/env python3
"""tools/vk_inventory_list.py [VULKAN_HPP]: writes gpu/shadps4/video_core/renderer_metal/
mtl_vk_inventory.inc, one BB_INVENTORY(name) per member of vulkan.hpp's DispatchLoaderDynamic, with
the header's platform conditions around them. The Metal layer's inventory (BB_METAL_INVENTORY=1)
wraps each loaded one to count the calls that reach the Vulkan driver (docs/RENDER_ADAPTER.md, M4
step 2). Run it again when the Vulkan headers change."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
header = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / 'deps/macos-arm64/include/vulkan/vulkan.hpp'
out = ROOT / 'gpu/shadps4/video_core/renderer_metal/mtl_vk_inventory.inc'

lines = header.read_text().splitlines()
start = next(i for i, l in enumerate(lines) if re.match(r'\s*class DispatchLoaderDynamic\b', l))
body, names = [], 0
for line in lines[start + 1:]:
    stripped = line.strip()
    if re.match(r'DispatchLoaderDynamic\(', stripped):
        break  # the members end at the constructors
    if re.match(r'#\s*(if|el|endif)', stripped):
        body.append(re.sub(r'#\s+', '#', stripped))
    elif m := re.match(r'PFN_vk\w+\s+(vk\w+)\s*=\s*0;', stripped):
        body.append(f'BB_INVENTORY({m.group(1)})')
        names += 1
# Drop conditional blocks left empty and unbalanced tails.
text = '\n'.join(body)
while True:
    cleaned = re.sub(r'#if[^\n]*\n(#el[^\n]*\n)*#endif\n?', '', text)
    if cleaned == text:
        break
    text = cleaned
opened = sum(l.startswith('#if') for l in text.splitlines()) - sum(l.startswith('#endif') for l in text.splitlines())
text += '\n#endif' * max(opened, 0)
out.write_text('// Generated by tools/vk_inventory_list.py from vulkan.hpp\'s DispatchLoaderDynamic: do not edit.\n'
               + text.strip() + '\n')
print(f'{names} functions -> {out.relative_to(ROOT)}')
